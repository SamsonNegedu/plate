package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"slices"
	"sort"
	"strings"
)

type operation struct {
	Summary     string                       `json:"summary"`
	Description string                       `json:"description"`
	Tags        []string                     `json:"tags"`
	Security    []map[string]json.RawMessage `json:"security"`
	Responses   map[string]json.RawMessage   `json:"responses"`
}

type spec struct {
	Info struct {
		Title       string `json:"title"`
		Description string `json:"description"`
	} `json:"info"`
	Paths map[string]map[string]operation `json:"paths"`
}

type row struct {
	method, path string
	op           operation
}

var methodOrder = []string{"get", "put", "post", "delete"}

// apiMarkdown renders the API reference from the OpenAPI document, so the doc cannot drift from the code.
func apiMarkdown(specJSON []byte) ([]byte, error) {
	var s spec
	if err := json.Unmarshal(specJSON, &s); err != nil {
		return nil, fmt.Errorf("reading the spec: %w", err)
	}
	byTag := map[string][]row{}
	for path, methods := range s.Paths {
		for method, op := range methods {
			tag := "other"
			if len(op.Tags) > 0 {
				tag = op.Tags[0]
			}
			byTag[tag] = append(byTag[tag], row{method: method, path: path, op: op})
		}
	}
	tags := make([]string, 0, len(byTag))
	for t := range byTag {
		tags = append(tags, t)
	}
	sort.Strings(tags)

	var b bytes.Buffer
	b.WriteString("# API reference\n\n")
	b.WriteString("<!-- Generated by `make generate` from internal/httpapi/openapi.json. Do not edit by hand. -->\n\n")
	fmt.Fprintf(&b, "%s\n\n", s.Info.Description)
	b.WriteString("All paths are under `/api/v1`. Every operation needs a session cookie unless it says *public*. ")
	b.WriteString("Errors are `application/problem+json` with a stable `code`, a `detail`, and a `request_id`. ")
	b.WriteString("The full machine-readable contract is `internal/httpapi/openapi.json`; the client types are generated from it.\n")
	for _, t := range tags {
		rows := byTag[t]
		sort.Slice(rows, func(i, j int) bool {
			if rows[i].path != rows[j].path {
				return rows[i].path < rows[j].path
			}
			return slices.Index(methodOrder, rows[i].method) < slices.Index(methodOrder, rows[j].method)
		})
		fmt.Fprintf(&b, "\n## %s\n\n| Method | Path | What it does | Auth | Responses |\n|---|---|---|---|---|\n", t)
		for _, r := range rows {
			auth := "session"
			if len(r.op.Security) == 0 {
				auth = "public"
			}
			codes := make([]string, 0, len(r.op.Responses))
			for c := range r.op.Responses {
				codes = append(codes, c)
			}
			sort.Strings(codes)
			fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s |\n",
				strings.ToUpper(r.method), r.path, cell(r.op.Summary), auth, strings.Join(codes, ", "))
		}
	}
	return b.Bytes(), nil
}

func cell(s string) string { return strings.ReplaceAll(strings.TrimSpace(s), "|", "\\|") }
